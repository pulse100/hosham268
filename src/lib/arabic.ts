/** توحيد الكتابة العربية للبحث: الهمزات، التاء المربوطة، الياء، التشكيل، «ال» التعريف */
export function normalizeAr(s: string) {
  return s
    .toLowerCase()
    .replace(/[ً-ٰٟـ]/g, "") // التشكيل والتطويل
    .replace(/[أإآٱ]/g, "ا")
    .replace(/ة/g, "ه")
    .replace(/ى/g, "ي")
    .replace(/ؤ/g, "و")
    .replace(/ئ/g, "ي")
    .replace(/[٠-٩]/g, (d) => String("٠١٢٣٤٥٦٧٨٩".indexOf(d)))
    .replace(/[^\p{L}\p{N}\s]/gu, " ")
    .replace(/\s+/g, " ")
    .trim();
}

/** كلمة بدون «ال» في بدايتها (البنوك ← بنوك) */
export const stripAl = (w: string) => (w.startsWith("ال") && w.length > 3 ? w.slice(2) : w);

